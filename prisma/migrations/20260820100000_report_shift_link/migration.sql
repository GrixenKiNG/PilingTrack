-- Отчёт знает свою смену.
--
-- ЗАЧЕМ. Смена (контур готовности) и сменный отчёт (выработка) до сих пор
-- жили как два несвязанных документа: наработка машины и выработка бригады
-- не сходились ни в одном запросе, а оператор вёл за смену две бумаги и мог
-- забыть одну. С этой колонкой сдача смены может требовать отправленного
-- отчёта, а отчёт становится содержанием передачи, а не вторым параллельным
-- документом.
--
-- ПОЧЕМУ NULLABLE И БЕЗ ВНЕШНЕГО КЛЮЧА. Отчёты, сделанные до 20.08.2026,
-- смены не знают, и восстанавливать связь задним числом нечем — угадывание
-- по дате и установке дало бы правдоподобную ложь в доказательной базе.
-- Внешнего ключа нет намеренно, как у lastEditedById рядом: смена живёт в
-- своём модуле со своим жизненным циклом, и удаление смены не должно
-- каскадом трогать подписанный отчёт.
--
-- RLS не трогаем: колонка добавляется в таблицу, у которой политика уже есть.

ALTER TABLE "Report" ADD COLUMN IF NOT EXISTS "shiftId" TEXT;

CREATE INDEX IF NOT EXISTS "Report_tenantId_shiftId_idx"
  ON "Report" ("tenantId", "shiftId");
