-- Требования к подписям переезжают из кода в справочник видов работ.
--
-- Контекст. До сих пор число и состав согласований выводились из риска прямо в
-- коде (requiredApprovalRoles): обычный — диспетчер, повышенный — диспетчер и
-- администратор. Владелец 16.08.2026 указал, что это не дело разработчика:
-- нормативы у каждой организации свои, и админ должен сам решать, сколько и
-- каких подписей требуют такие-то работы — вплоть до «на опасное достаточно
-- одного ответственного за безопасность».
--
-- Поэтому требование становится свойством СТРОКИ справочника, а не константой.
--
-- Почему наряд ХРАНИТ СВОЙ СНИМОК требования, а не смотрит в справочник. Если
-- читать требование живьём, любая правка вида работ переписывала бы прошлое:
-- подписанные вчера наряды разом стали бы недоподписанными (админ добавил
-- роль) или, наоборот, задним числом «согласованными» без нужной подписи (админ
-- роль убрал). Снимок делается при оформлении и обновляется при правке наряда —
-- а правка и без того аннулирует подписи, так что расхождения не возникает.
--
-- allowAuthorApproval — отдельный вопрос, который тоже нельзя решать за
-- заказчика: может ли автор подписать собственный наряд. Значения по умолчанию
-- ниже ТОЧНО повторяют сегодняшнее поведение кода, чтобы миграция ничего не
-- поменяла в работе: обычный риск — автору можно (запрет был снят намеренно,
-- иначе контур вставал: наряды заводит админ, замещая механика, и подписать их
-- больше некому), повышенный — нельзя.

ALTER TABLE "PermitWorkType"
  ADD COLUMN "requiredApprovals"   "WorkPermitApprovalRole"[] NOT NULL DEFAULT ARRAY['DISPATCHER']::"WorkPermitApprovalRole"[],
  ADD COLUMN "allowAuthorApproval" BOOLEAN NOT NULL DEFAULT true;

ALTER TABLE "WorkPermit"
  ADD COLUMN "requiredApprovals"   "WorkPermitApprovalRole"[] NOT NULL DEFAULT ARRAY[]::"WorkPermitApprovalRole"[],
  ADD COLUMN "allowAuthorApproval" BOOLEAN NOT NULL DEFAULT true;

-- Виды работ повышенного риска получают сегодняшнее правило: две подписи,
-- автору свой наряд подписывать нельзя.
UPDATE "PermitWorkType"
SET "requiredApprovals"   = ARRAY['DISPATCHER', 'ADMIN']::"WorkPermitApprovalRole"[],
    "allowAuthorApproval" = false
WHERE "defaultRisk" = 'ELEVATED';

-- Существующие наряды получают снимок ровно того правила, по которому они
-- оформлялись. Без этого шага у них остался бы пустой список — то есть
-- «подписи не нужны вовсе», и всё уже выписанное молча стало бы согласованным.
UPDATE "WorkPermit"
SET "requiredApprovals" = CASE
      WHEN "risk" = 'ELEVATED' THEN ARRAY['DISPATCHER', 'ADMIN']::"WorkPermitApprovalRole"[]
      ELSE ARRAY['DISPATCHER']::"WorkPermitApprovalRole"[]
    END,
    "allowAuthorApproval" = ("risk" <> 'ELEVATED');
