-- Простой обязан иметь причину — проверка на уровне базы.
--
-- Миграция production_intervals сделала reasonId необязательным: интервал v3
-- пишет причину текстом (reasonText) и категорией, а справочный ключ остаётся
-- у записей старого пути. Само по себе это верно, но в результате база стала
-- принимать простой вообще без причины — ни ссылки на справочник, ни текста.
--
-- Прикладная проверка это уже запрещает (work-interval.ts, DOWNTIME_REASON_
-- REQUIRED), однако она действует только на одном пути записи. Ограничение
-- закрывает остальные.
--
-- Перерыв (BREAK) причины не требует — это не простой, а нормальный элемент
-- смены. Записи старого пути с kind IS NULL проверку проходят: сравнение с
-- NULL даёт NULL, и CHECK такую строку принимает.
ALTER TABLE "ReportDowntime"
  ADD CONSTRAINT "ReportDowntime_reason_present"
  CHECK (NOT ("kind" = 'DOWNTIME' AND "reasonId" IS NULL AND "reasonText" IS NULL));
