--
-- ЗАЧЕМ. Скорость ветра — рабочее ограничение, а не справка: в руководстве
-- Liebherr LB 20 работы прекращают при 20 м/с, а при прогнозе свыше 36 м/с
-- стрелу переводят в транспортное положение. Чтобы показывать оператору ветер
-- на его площадке, нужна точка на карте, а у объекта её до сих пор не было.
--
-- ПОЧЕМУ NULLABLE. Объекты уже заведены, координат у них нет, и выдумывать их
-- нельзя. Пока координат нет, экран просит ввести ветер руками — это рабочий
-- путь, а не заглушка.
--
-- RLS не трогаем: политика у таблицы уже есть, колонки её не меняют.

