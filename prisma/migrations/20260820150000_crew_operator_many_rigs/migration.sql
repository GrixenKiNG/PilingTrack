-- это проверяет assertEquipmentNotDoubleBooked. Снимается только ограничение
-- со стороны человека, не со стороны машины.
--
-- Обычный индекс по operatorId уже есть (Crew_operatorId_idx) — запросы
-- «бригады оператора» останутся индексными.

