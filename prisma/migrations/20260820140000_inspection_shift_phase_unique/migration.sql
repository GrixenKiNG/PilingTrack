-- Одна фаза смены — один осмотр.
--
-- ЗАЧЕМ. Осмотр фазы выбирается по паре «смена + фаза» первым совпадением.
-- Две записи одной фазы (двойное нажатие, второй телефон) сделали бы этот
-- выбор произвольным: оператор заполнял бы одну, а сравнение состояния и
-- передача смены читали бы другую — молча и без признака ошибки.
--
-- ПОЧЕМУ ОБЫЧНЫЙ UNIQUE, А НЕ ЧАСТИЧНЫЙ. Postgres считает NULL различными,
-- поэтому осмотры без смены (плановое ТО механика, всё до 20.08.2026)
-- ограничением не задеты — их может быть сколько угодно.
--
-- Обычный индекс с той же тройкой снимаем: уникальный обслуживает те же
-- запросы, а два одинаковых индекса зря тормозят запись.

DROP INDEX IF EXISTS "Inspection_tenantId_shiftId_phase_idx";

CREATE UNIQUE INDEX IF NOT EXISTS "Inspection_tenantId_shiftId_phase_key"
  ON "Inspection" ("tenantId", "shiftId", "phase");
