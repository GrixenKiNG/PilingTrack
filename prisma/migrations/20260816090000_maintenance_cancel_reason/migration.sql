-- Причина отмены наряда ТО.
--
-- Закрытие наряда уже требует описания выполненных работ, а отмена оставалась
-- бесплатной: статус переводили в CANCELLED одним щелчком, и наряд исчезал из
-- работы без единого слова о том, почему. Для механика и диспетчера это
-- неотличимо от «потерялся»: заявка была, работы нет, спросить не с кого.
--
-- Отдельная колонка, а не переиспользование description/workDone: описание —
-- это зачем наряд открывали, workDone — что сделали. Причина отмены отвечает
-- на третий вопрос и в закрытых нарядах должна оставаться пустой.
ALTER TABLE "MaintenanceRecord" ADD COLUMN "cancelReason" TEXT;
