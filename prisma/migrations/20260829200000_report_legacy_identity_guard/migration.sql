-- Возврат защиты от дублей для отчётов, не привязанных к смене v3.
--
-- Миграция shift_report_identity сняла @@unique([userId, siteId, date]) и
-- заменила его на уникальность по (tenantId, shiftId): в модели v3 отчёт
-- принадлежит смене, и одна смена на пользователя в сутки больше не догма.
--
-- Но shiftId необязателен, а в PostgreSQL NULL в уникальном индексе считается
-- отличным от любого другого NULL. Отчёты старого пути смены не имеют (на
-- 29.08.2026 таких 174 из 184, то есть 95 %), и для них новый ключ не
-- ограничивает ничего: система молча приняла бы два отчёта одного человека по
-- одному объекту за одну дату.
--
-- Частичный индекс возвращает прежнюю гарантию ровно там, где она работала, и
-- не мешает отчётам, у которых смена есть.
CREATE UNIQUE INDEX IF NOT EXISTS "Report_user_site_date_without_shift_key"
  ON "Report" ("userId", "siteId", "date")
  WHERE "shiftId" IS NULL;
