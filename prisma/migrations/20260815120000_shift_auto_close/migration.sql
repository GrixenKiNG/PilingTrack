-- Автозакрытие смены по окончании производственных суток.
--
-- Смена закрывалась единственным способом — диспетчер принимал сданную
-- передачу. Не сдали или не приняли — смена висела «в работе» бесконечно, и
-- на экране техготовности каждое утро встречал вчерашний «вечный процесс».
--
-- Планировщик теперь закрывает такие смены сам, но след этого действия обязан
-- отличаться от нормального закрытия: принятая смена — это работа, принятая
-- человеком, а автозакрытая — повод спросить, почему её не сдали. Отдельная
-- отметка времени вместо нового состояния выбрана намеренно: состояние CLOSED
-- уже разобрано по всему коду и интерфейсу, добавление седьмого значения в
-- enum потребовало бы трогать каждый switch ради одного признака.
ALTER TABLE "Shift" ADD COLUMN "autoClosedAt" TIMESTAMPTZ(3);

-- Разбор «что закрылось само» — запрос диспетчера, а не редкий отчёт.
CREATE INDEX "Shift_tenantId_autoClosedAt_idx" ON "Shift" ("tenantId", "autoClosedAt");
