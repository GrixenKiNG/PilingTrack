import { redirect } from 'next/navigation';
import { readPageSessionUser } from '@/lib/page-session';

/**
 * Модуль «ТБ и допуски» открыт КАЖДОЙ роли, и поэтому лежит своей группой, а
 * не под `admin/layout.tsx`.
 *
 * Решение владельца 13.09.2026: инструктаж проходит каждый работник, значит
 * дорога к своим инструктажам нужна каждому — машинисту и помощнику в том
 * числе, а администраторская раскладка уводила их на своё рабочее место.
 *
 * Права роли это НЕ отменяет: какие вкладки показать, решает bootstrap
 * контура готовности. Роль без прав инженера ОТ увидит только «Мой допуск» —
 * свои документы, свои инструктажи и свою проверку знаний, — а чужие допуски
 * ей по-прежнему закрыты, и закрыты на сервере, а не скрытием вкладки.
 */
export default async function SafetySectionLayout({ children }: { children: React.ReactNode }) {
  // Контекст организации обязателен: без него строгая политика RLS не отдаёт
  // строку пользователя и раздел уходит в круг переходов (см. admin/layout).
  const user = await readPageSessionUser();
  if (!user) redirect('/login');

  return <>{children}</>;
}
