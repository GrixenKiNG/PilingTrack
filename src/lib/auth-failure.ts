import { NextResponse } from 'next/server';

/**
 * Ответ на отказ `requireAuth` для маршрутов, которые показывают его человеку
 * по-русски (мобильное место машиниста и помощника, происшествия).
 *
 * ПОЧЕМУ НЕ ВСЕГДА 401. `requireAuth` отдаёт настоящие 401/403 для отсутствующей
 * или недействительной сессии, но 500, когда сама проверка упала — недоступна база
 * или кэш. Маршруты переписывали любой отказ в «Войдите в систему», и при
 * недоступной базе машинист шёл заново входить, хотя сессия цела и после
 * восстановления работает без входа (аудит 16.10.2026, P2 D-20261016-002).
 *
 * Отказ остаётся fail-closed: команда без проверенного пользователя не
 * выполняется ни в том, ни в другом случае; различается только то, что видит
 * человек. 503 клиент мобильного места уже считает временным сбоем.
 */
export function authFailureResponse(error: Response | null | undefined): NextResponse {
  if (error && error.status >= 500) {
    return NextResponse.json(
      { error: 'Сервис временно недоступен. Повторите через минуту, входить заново не нужно.' },
      { status: 503, headers: { 'Retry-After': '15' } },
    );
  }
  return NextResponse.json({ error: 'Войдите в систему' }, { status: 401 });
}
