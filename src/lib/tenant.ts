import { ServiceError } from '@/lib/service-error';

/**
 * Организация запроса — из сессии и только из неё.
 *
 * ПОЧЕМУ ОТДЕЛЬНАЯ ФУНКЦИЯ. По маршрутам было рассыпано 85 повторений вида
 * `user.tenantId ?? process.env.DEFAULT_TENANT_ID`. Замысел понятен — не
 * уронить запрос, если у пользователя почему-то нет организации, — но
 * следствие обратное: аутентифицированный пользователь без организации молча
 * получал доступ к данным организации по умолчанию. Половина этих строк
 * вдобавок кончалась `?? ''`, и тогда запрос уходил в базу с пустым тенантом.
 *
 * Ответ на «организации нет» один и он же единственно безопасный: отказать.
 * Такого пользователя нельзя обслужить правильно — можно только обслужить
 * чужими данными.
 *
 * ПОЧЕМУ НЕ В `lib/auth`. Маршрутные тесты подменяют весь модуль `@/lib/auth`
 * ради `requireAuth`. Помощник, живущий там же, в тестах становился бы
 * заглушкой — то есть проверка организации в них не исполнялась бы вовсе.
 * Здесь он настоящий и в тестах тоже.
 *
 * Прикладные фильтры по `tenantId` этим не отменяются: строгие политики RLS
 * на бою — вторая линия, а не первая.
 */
export function requireTenantId(user: { tenantId?: string | null } | null | undefined): string {
  const tenantId = user?.tenantId;
  if (!tenantId) {
    throw new ServiceError('Организация пользователя не определена', 403);
  }
  return tenantId;
}
