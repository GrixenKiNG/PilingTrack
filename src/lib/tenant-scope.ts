import { ServiceError } from '@/lib/service-error';

/**
 * Тенант обязателен — иначе запрос не выполняется.
 *
 * Правило проекта (CLAUDE.md): при отсутствии тенанта нужно падать, а не
 * снимать фильтр. Причина записана кровью: `IS NULL OR tenantId` в майском
 * инциденте отдал строки всех организаций сразу. Тот же провал получается и
 * без SQL — из `if (tenantId) where.tenantId = tenantId`, потому что пустой
 * тенант просто убирает условие, и выборка становится общей.
 *
 * Пустая строка приравнена к отсутствию намеренно: маршруты собирают тенант
 * как `user.tenantId ?? DEFAULT_TENANT_ID ?? ''`, и без этой проверки в
 * фильтр уходило бы `''` — то есть либо пустой ответ без объяснения, либо
 * снятый фильтр там, где значение проверяют на истинность.
 *
 * Функция появилась потому, что то же самое было написано трижды по частным
 * копиям — в users, telegram и readiness, причём последняя бросала голый
 * Error и превращала отсутствие тенанта в отказ сервера вместо ответа 400.
 */
export function requireTenantId(tenantId: string | null | undefined): string {
  const value = tenantId?.trim();
  if (!value) {
    throw new ServiceError('Контекст организации не определён', 400);
  }
  return value;
}
