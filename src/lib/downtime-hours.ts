/**
 * Простой: интервал, а не число часов (решение владельца 19.09.2026).
 *
 * ЧТО БЫЛО И ПОЧЕМУ ИЗМЕНИЛОСЬ. До этой даты простой вводился числом часов и
 * округлялся ВВЕРХ до целого: двадцать минут ожидания бетона становились
 * часом. Обоснование было честным — округление вниз обнуляло короткие
 * остановки, из которых складывается смена. Но цена оказалась выше: отчёт
 * переставал быть измерением. Полчаса и полные пятьдесят пять минут
 * записывались одинаково, а шесть коротких остановок превращались в шесть
 * часов простоя, которых не было. Спорить с подрядчиком такими цифрами нельзя:
 * первая же проверка по факту обнаруживает завышение, и тогда под сомнением
 * оказывается весь журнал, включая правдивую его часть.
 *
 * ЧТО ВМЕСТО. Оператор указывает НАЧАЛО И КОНЕЦ, длительность считает сервер.
 * Это убирает округление как таковое и попутно отвечает на вопрос, которого
 * число часов не отвечало вовсе: КОГДА машина стояла. Простой с 10:20 до 10:50
 * и простой с 06:00 до 06:30 — разные события для того, кто разбирает смену,
 * хотя оба «полчаса».
 *
 * ЕДИНИЦА ХРАНЕНИЯ ОСТАЁТСЯ ЧАСОМ. `ReportDowntime.duration` — часы дробным
 * числом, рядом лежат `startedAt`/`endedAt`/`durationSeconds`. Менять единицу
 * значило бы переписать все агрегаты, аналитику и 169 уже сданных отчётов ради
 * записи, которую и так видно с точностью до секунды.
 *
 * ПОЧЕМУ ОДИН ВЛАДЕЛЕЦ. Простой вводят с телефона машиниста и из формы отчёта,
 * а правят поправкой. Три места со своим расчётом разошлись бы на первой же
 * правке, и одна и та же остановка попадала бы в отчёт по-разному в
 * зависимости от того, кто её записал.
 *
 * ПОЧЕМУ В lib, А НЕ В ДОМЕНЕ ОТЧЁТОВ. Раньше файл лежал в
 * `modules/reports/domain/`, но пользуется им весь продукт: формат простоя
 * рисуют экраны машиниста, карточки техники и аналитика, а `DOWNTIME_MAX_HOURS`
 * держит границу в общих схемах валидации. Это общий словарь приложения, а не
 * внутренность модуля отчётов, и каждый такой импорт был обходом границы
 * модуля — ровно того правила, которое проверяет `isPublicModuleEntry`.
 */

/** Больше суток один простой длиться не может. */
export const DOWNTIME_MAX_HOURS = 24;

/**
 * Длительность интервала в часах — без округления.
 *
 * Конец раньше начала означает переход через полночь: ночная смена начинается
 * вечером и заканчивается утром, и простой в ней — обычное дело. Сдвигаем
 * конец на сутки вперёд, а не отвергаем ввод: отказ здесь заставил бы
 * машиниста в три часа ночи считать, какую дату ему подставить.
 */
export function downtimeHoursBetween(startedAt: Date, endedAt: Date): number {
  const start = startedAt.getTime();
  const end = endedAt.getTime();
  const span = end >= start ? end - start : end - start + 86_400_000;
  return span / 3_600_000;
}

/**
 * Простой для показа: часы и минуты, как оно и было.
 *
 * ПОЧЕМУ НЕ ОБЩИЙ `formatHours`. Тот же помощник рисует отработанное время
 * смены и склоняет единицы иначе; здесь формат обязан совпадать во всех
 * местах, где простой сравнивают между собой.
 *
 * Секунды не показываем: интервал задаётся с точностью до минуты, и «1 ч 29 мин
 * 59 с» — точность, которой во вводе не было.
 */
export function formatDowntimeHours(hours: number | null | undefined): string {
  if (hours == null || !Number.isFinite(hours) || hours <= 0) return '0 ч';

  const totalMinutes = Math.round(hours * 60);
  const wholeHours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;

  if (wholeHours === 0) return `${minutes} мин`;
  if (minutes === 0) return `${wholeHours} ч`;
  return `${wholeHours} ч ${minutes} мин`;
}
