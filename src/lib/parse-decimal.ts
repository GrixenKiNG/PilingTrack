/**
 * Разбор числа, набранного в текстовом поле админки.
 *
 * В русской раскладке дробную часть набирают запятой («1,5»), но `Number('1,5')`
 * даёт NaN — поле молча не сохранялось. Ещё одна ловушка: значение, показанное
 * через `toLocaleString('ru-RU')`, содержит неразрывный пробел-разделитель тысяч
 * («1 000,00») — `Number(...)` на нём тоже NaN, из-за чего панель сведений не
 * могла сохранить такую марку (W62 №3).
 *
 * Единственный способ прочитать число из текстового поля админки.
 *
 * Возвращает `null` для пустой строки и для мусора («abc», «1,2,3») — вызывающая
 * сторона сама решает, что делать с нечислом, но никогда не получает NaN.
 */
export function parseDecimalInput(text: string): number | null {
  // Пробелы (в т.ч. неразрывные) — разделители тысяч; запятая заменяется точкой.
  const cleaned = text.replace(/\s/g, '').replace(',', '.');
  if (!/^[+-]?(\d+(\.\d*)?|\.\d+)$/.test(cleaned)) return null;
  const value = Number(cleaned);
  return Number.isFinite(value) ? value : null;
}
