/** Сколько вопросов в одной попытке. */
export const QUESTIONS_PER_ATTEMPT = 8;

const BY_ID = new Map(KNOWLEDGE_BANK.map((question) => [question.id, question]));

export function findQuestion(id: string): KnowledgeQuestion | undefined {
  return BY_ID.get(id);
}

/**
 * Набор вопросов на попытку: по темам, в случайном порядке.
 *
 * Доли фиксированы, чтобы бурение не выпало целиком: три по забивке, две по
 * бурению, три общих. Внутри темы выбор случайный, поэтому два набора подряд
 * практически не совпадают.
 */
export function buildAttempt(random: () => number = Math.random): KnowledgeQuestion[] {
  const pick = (topic: KnowledgeTopic, count: number) => {
    const pool = KNOWLEDGE_BANK.filter((question) => question.topic === topic);
    // Перемешивание Фишера — Йетса на копии: сам банк не трогаем.
    const shuffled = [...pool];
    for (let i = shuffled.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }
    return shuffled.slice(0, count);
  };

  const chosen = [...pick('PILING', 3), ...pick('DRILLING', 2), ...pick('GENERAL', 3)];
  for (let i = chosen.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [chosen[i], chosen[j]] = [chosen[j], chosen[i]];
  }
  return chosen;
}

/**
 * Итог попытки считает сервер по своему банку, а не по тому, что прислал
 * телефон. Экран показывает верный ответ сразу — это обучение, а не экзамен, —
 * но в журнал уходит то, что человек действительно нажал.
 */
export function scoreAttempt(picks: {questionId: string; picked: number}[]): {
  total: number;
  correct: number;
  wrongIds: string[];
} {
  let correct = 0;
  const wrongIds: string[] = [];
  for (const pick of picks) {
    const question = BY_ID.get(pick.questionId);
    if (!question) continue;
    if (question.correct === pick.picked) correct++;
    else wrongIds.push(question.id);
  }
  return {total: picks.length, correct, wrongIds};
}

