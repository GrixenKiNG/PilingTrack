/**
 * Слова для уровней и состояний неисправности — в поле, а не в журнале.
 *
 * ПОЧЕМУ ОТДЕЛЬНО ОТ `readiness/domain/defects/types.ts`. Там та же шкала
 * названа «Критичный / Высокий / Обычный / Низкий»: диспетчеру нужна шкала,
 * по которой сортируют и сравнивают. Человеку у машины шкала не говорит
 * ничего — ему нужно следствие: работать нельзя или можно. Это не дубль, а
 * два регистра одной шкалы, и держать их врозь честнее, чем выбирать один и
 * заставлять вторую сторону читать чужой язык.
 *
 * ПОЧЕМУ ОБЩИЙ ФАЙЛ, А НЕ КОНСТАНТА В ЭКРАНЕ. Экранов с этими словами теперь
 * два — машиниста и помощника, — и разъехавшиеся копии означали бы, что одна
 * и та же поломка на двух телефонах называется по-разному.
 *
 * Пропущенный код выводится как есть: заметно, что перевода нет, и это лучше,
 * чем показать не тот уровень.
 */

