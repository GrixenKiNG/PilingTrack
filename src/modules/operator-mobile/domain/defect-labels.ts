/** Значения `DefectStatus`. Закрытые до полевых экранов не доходят. */
export const DEFECT_STATUS_FIELD_LABELS: Record<string, string> = {
  OPEN: 'Не начат',
  IN_WORK: 'В работе',
};

/** Уровень, при котором предупреждение красное, а не жёлтое. */
export function isAlarmingSeverity(severity: string): boolean {
  return severity === 'CRITICAL' || severity === 'HIGH';
}
