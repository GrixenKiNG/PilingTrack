/**
 * Средства индивидуальной защиты: каталог и правило прохождения шага.
 *
 * ПОЧЕМУ КАТАЛОГ В КОДЕ. Перечень СИЗ для свайных работ меняется не чаще
 * текста инструкции, который тоже живёт в коде (решение владельца 13.09.2026).
 * Отдельный справочник с экраном администрирования ради шести строк — это
 * работа, которая не окупится.
 *
 * ПОЧЕМУ НЕХВАТКА НЕ ЗАПИРАЕТ ЭКРАН. Запертый работник отметит, что каска
 * есть, лишь бы начать смену, — и мы получим ложную запись вместо честной.
 * Отметка о нехватке даёт красное предупреждение оператору и диспетчеру: это
 * работает, а запрет учит врать. Шаг закрывает сам факт ПРОВЕРКИ, а не
 * полнота комплекта — ровно та же логика, по которой просроченный документ
 * предупреждает, но не запирает (см. `derivePhase`).
 *
 * Чистые данные и функции: файл попадает в браузерный пакет.
 */

export interface PpeItem {
  code: string;
  label: string;
  /** Короткое пояснение под строкой — что именно проверить. */
  hint: string;
}

export const PPE_ITEMS: readonly PpeItem[] = [
  { code: 'HELMET', label: 'Каска', hint: 'Целая, с застёгнутым подбородочным ремнём' },
  { code: 'VEST', label: 'Сигнальный жилет', hint: 'Светоотражающие полосы не затёрты' },
  { code: 'BOOTS', label: 'Защитная обувь', hint: 'С защитным подноском, подошва цела' },
  { code: 'GLOVES', label: 'Перчатки', hint: 'Без порывов, по размеру' },
  { code: 'GLASSES', label: 'Защитные очки', hint: 'Стёкла не мутные, дужки целы' },
  { code: 'EARMUFFS', label: 'Защита слуха', hint: 'Наушники или беруши — рядом с молотом обязательны' },
];

export const PPE_LABELS: Record<string, string> = Object.fromEntries(
  PPE_ITEMS.map((item) => [item.code, item.label]),
);

/**
 * Пройден ли шаг СИЗ на эти производственные сутки.
 *
 * Проверка засчитывается за сутки, а не за смену: человек, переброшенный на
 * вторую установку в тот же день, каску второй раз не надевает.
 */
export function ppeConfirmedFor(
  checks: ReadonlyArray<{ productionDate: Date | string }>,
  productionDate: string,
): boolean {
  return checks.some((check) => toDay(check.productionDate) === productionDate);
}

/** Календарный день записи в виде `ГГГГ-ММ-ДД`. */
export function toDay(value: Date | string): string {
  if (typeof value === 'string') return value.slice(0, 10);
  // Дата производственных суток хранится как DATE — у неё нет часов, и
  // переводить её в местное время нельзя: полночь UTC уедет на вчера.
  return value.toISOString().slice(0, 10);
}

/** Строки предупреждения о нехватке — то, что увидят оператор и диспетчер. */
export function missingPpeLabels(missing: readonly string[]): string[] {
  return missing.map((code) => PPE_LABELS[code] ?? code);
}
