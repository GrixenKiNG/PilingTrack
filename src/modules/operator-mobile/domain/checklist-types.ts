/**
 * Словарь ответов и форма пункта чек-листа оператора.
 *
 * ПОЧЕМУ ТРИ ОТВЕТА, А НЕ ГАЛОЧКА. Галочка отвечает на вопрос «посмотрел ли
 * оператор», а нужен ответ на вопрос «что он увидел». Между «всё хорошо» и
 * «неисправно» лежит замечание — течь, которая пока капает, обрыв одной пряди
 * троса. Если этого состояния нет, оператор ставит галочку и едет работать, а
 * механик узнаёт о течи, когда узел встанет.
 *
 * «Не применимо» здесь нет намеренно: пункты, которых на этой машине или при
 * этой погоде быть не должно, отсеиваются до показа. Кнопка «неприменимо» на
 * осмотре мачты — это способ не осматривать мачту.
 */
export type OperatorAnswer = 'OK' | 'REMARK' | 'FAULT';

/** Этап смены, к которому привязан чек-лист. */
export type ChecklistStage =
  | 'PRESHIFT_INSPECTION' // предсменный осмотр, машина холодная
  | 'EO_BEFORE' // пуск, прогрев, холостая проверка, ЕО перед работой
  | 'SITE_READY' // готовность площадки к производству работ
  | 'TB_PILING' // ТБ: забивка свай
  | 'TB_DRILLING' // ТБ: лидерное бурение
  | 'EO_AFTER'; // послесменное обслуживание и осмотр

/**
 * Внешние условия смены. Определяют, какие пункты вообще показывать.
 *
 * ПОЧЕМУ УСЛОВИЯ, А НЕ ОДИН БОЛЬШОЙ СПИСОК. Требование к чек-листу —
 * «только самое критичное». Но критичное зимой (наледь под гусеницами,
 * загустевшее гидромасло) и критичное в распутицу (просадка основания) —
 * это разные пункты. Один общий список, где половина пунктов круглый год
 * не к месту, оператор перестаёт читать через неделю.
 */
export type ShiftCondition =
  | 'FROST' // мороз: температура ниже порога
  | 'RAIN' // дождь, мокрый снег, распутица
  | 'DARK' // работа в темноте
  | 'WIND'; // сильный ветер

/**
 * Узел установки, к которому относится пункт. Пункты про молот не должны
 * появляться на буровой, пункты про вращатель — на чистом копре.
 * Подбор идёт по Equipment.hammerKind и Equipment.isCombined —
 * поля уже есть в карточке техники, отдельного справочника не нужно.
 */
export type ChecklistUnit = 'HAMMER' | 'ROTATOR';

/**
 * Насколько серьёзна неисправность по этому пункту.
 *
 * ПОЧЕМУ НЕТ УРОВНЯ «СТОП». Телеметрии на установках нет, и программа не может
 * знать состояние машины лучше человека, который на ней работает. Запретить
 * работу по ответу в чек-листе значило бы остановить объект по нажатию кнопки
 * на телефоне — без возможности проверить. Поэтому неисправность даёт красное
 * предупреждение оператору и диспетчеру, заводит дефект и остаётся на виду,
 * пока дефект не закрыт. Решение о работе принимает человек.
 */
export type ItemSeverity =
  | 'ALERT' // неисправность — красное предупреждение обоим
  | 'NOTE'; // замечание — жёлтое, в работу механику в плановом порядке

/** Числовой замер внутри пункта: долив жидкости, время прогрева, топливо. */
export interface ChecklistMeasure {
  key: string;
  label: string;
  unit: string;
  /** Замер обязателен при этих ответах. Долив спрашиваем только при замечании. */
  requiredOn?: OperatorAnswer[];
}

export interface ChecklistItem {
  id: string;
  text: string;
  /** Короткая подсказка «на что смотреть». Одна строка, без инструкции на лист. */
  hint?: string;
  /** Красное предупреждение при неисправности. Иначе жёлтое замечание. */
  severity: ItemSeverity;
  /** Фото обязательно, если ответ хуже «норма». Доказательство для механика. */
  photoOnIssue?: boolean;
  measure?: ChecklistMeasure;
  onlyWhen?: ShiftCondition[];
  unit?: ChecklistUnit;
}

/**
 * Секция чек-листа — узел машины или этап работы.
 *
 * Двенадцать пунктов сплошной лентой на телефоне ищутся хуже, чем те же
 * двенадцать под шестью заголовками: оператор помнит, что течь была «где-то
 * в гидравлике», и идёт сразу туда.
 */
export interface ChecklistSection {
  id: string;
  title: string;
  items: ChecklistItem[];
}

export interface ChecklistDefinition {
  stage: ChecklistStage;
  /** Ключ версии. Меняется вместе с составом пунктов — снимок уходит в базу. */
  version: string;
  title: string;
  /** Зачем этот чек-лист — показывается оператору одной строкой над списком. */
  purpose: string;
  sections: ChecklistSection[];
}

/** Все пункты определения одним списком. */
export function checklistItems(definition: ChecklistDefinition): ChecklistItem[] {
  return definition.sections.flatMap((section) => section.items);
}
