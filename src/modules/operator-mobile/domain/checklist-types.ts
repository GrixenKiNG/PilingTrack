/**
 * Словарь ответов и форма пункта чек-листа оператора.
 *
 * ПОЧЕМУ ЧЕТЫРЕ ОТВЕТА, А НЕ ГАЛОЧКА. Галочка отвечает на вопрос «посмотрел ли
 * оператор», а нужен ответ на вопрос «что он увидел». Между «всё хорошо» и
 * «работать нельзя» лежит замечание — течь, которая пока капает, обрыв одной
 * пряди троса. Если этого состояния нет, оператор ставит галочку и едет
 * работать, а механик узнаёт о течи, когда узел встанет.
 *
 * NA — «не применимо»: на установке без молота пункт про молот не должен
 * требовать ответа и не должен считаться пройденным.
 */
export type OperatorAnswer = 'OK' | 'REMARK' | 'FAULT' | 'NA';

/** Этап смены, к которому привязан чек-лист. */
export type ChecklistStage =
  | 'PRESHIFT_INSPECTION' // предсменный осмотр, машина холодная
  | 'EO_BEFORE' // пуск, прогрев, холостая проверка, ЕО перед работой
  | 'SITE_READY' // готовность площадки к производству работ
  | 'TB_PILING' // ТБ: забивка свай
  | 'TB_DRILLING' // ТБ: лидерное бурение
  | 'EO_AFTER'; // послесменное обслуживание и осмотр

/**
 * Внешние условия смены. Определяют, какие пункты вообще показывать.
 *
 * ПОЧЕМУ УСЛОВИЯ, А НЕ ОДИН БОЛЬШОЙ СПИСОК. Требование к чек-листу —
 * «только самое критичное». Но критичное зимой (наледь под гусеницами,
 * загустевшее гидромасло) и критичное в распутицу (просадка основания) —
 * это разные пункты. Один общий список, где половина пунктов круглый год
 * не к месту, оператор перестаёт читать через неделю. Поэтому базовый
 * список короткий, а сезонные пункты добавляются по факту погоды.
 */
export type ShiftCondition =
  | 'FROST' // мороз: температура ниже порога
  | 'RAIN' // дождь, мокрый снег, распутица
  | 'DARK' // работа в темноте
  | 'WIND'; // сильный ветер

/**
 * Узел установки, к которому относится пункт. Пункты про молот не должны
 * появляться на буровой, пункты про вращатель — на чистом копре.
 * Подбор идёт по Equipment.hammerKind и Equipment.isCombined —
 * поля уже есть в карточке техники, отдельного справочника не нужно.
 */
export type ChecklistUnit = 'HAMMER' | 'ROTATOR';

/** Числовой замер внутри пункта: долив жидкости, показание счётчика. */
export interface ChecklistMeasure {
  key: string;
  label: string;
  unit: string;
  /** Замер обязателен при этом ответе. Долив спрашиваем только при замечании. */
  requiredOn?: OperatorAnswer[];
}

export interface ChecklistItem {
  id: string;
  text: string;
  /** Короткая подсказка «на что смотреть». Одна строка, без инструкции на лист. */
  hint?: string;
  /**
   * Неисправность по этому пункту запрещает работу до решения диспетчера.
   * Не всё критично: разбитое зеркало — замечание, трещина в мачте — стоп.
   */
  blocking: boolean;
  /** Фото обязательно, если ответ хуже OK. Доказательство для механика. */
  photoOnIssue?: boolean;
  measure?: ChecklistMeasure;
  onlyWhen?: ShiftCondition[];
  unit?: ChecklistUnit;
}

export interface ChecklistDefinition {
  stage: ChecklistStage;
  /** Ключ версии. Меняется вместе с составом пунктов — снимок уходит в базу. */
  version: string;
  title: string;
  /** Зачем этот чек-лист — показывается оператору один строкой над списком. */
  purpose: string;
  items: ChecklistItem[];
}
