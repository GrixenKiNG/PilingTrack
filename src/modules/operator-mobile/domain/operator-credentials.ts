/**
 * Ознакомление с инструкцией и проверка знаний живут в документах работника.
 *
 * ПОЧЕМУ ТАК, А НЕ ОТДЕЛЬНАЯ ТАБЛИЦА. Это ровно то, чем является документ
 * работника: запись «у человека есть действующее подтверждение» со сроком.
 * Справочник видов документов уже ведёт администратор, и обе записи появляются
 * в карточке пользователя рядом с медсправкой и удостоверением — диспетчер
 * видит их там, где привык, без нового экрана.
 *
 * ПОЧЕМУ НЕ ЧЕРЕЗ OperatorShiftEvidence. Свидетельства смены требуют смены, а
 * инструктаж и проверка знаний проходят ДО её открытия: привязывать их было бы
 * не к чему.
 */

/** Виды документов, которые модуль заводит сам. Имена — ключ поиска. */
export const BRIEFING_DOCUMENT_TYPE = 'Ознакомление с инструкцией по свайным работам';
export const KNOWLEDGE_DOCUMENT_TYPE = 'Проверка знаний по охране труда';

/**
 * Оба вида создаются необязательными: их отсутствие не должно давать красное
 * предупреждение само по себе — за это отвечает порядок фаз, который не
 * пропускает дальше без инструктажа и проверки. Отмечать их обязательными или
 * нет — решение администратора, а не программы.
 */
export const SYSTEM_DOCUMENT_TYPES = [
  {
    name: BRIEFING_DOCUMENT_TYPE,
    requiresExpiry: false,
    leadTimeDays: 30,
    notes: 'Заводится автоматически при ознакомлении. Номер — версия инструкции.',
  },
  {
    name: KNOWLEDGE_DOCUMENT_TYPE,
    requiresExpiry: true,
    leadTimeDays: 7,
    notes: 'Заводится автоматически по итогу проверки. Номер — результат.',
  },
] as const;

/** Ознакомлен ли оператор с действующей версией инструкции. */
export function briefingUpToDate(
  acknowledgedVersion: string | null,
  currentVersion: string,
): boolean {
  return acknowledgedVersion === currentVersion;
}

/** Действует ли результат проверки знаний. */
export function knowledgeValid(validUntil: Date | null, now: Date): boolean {
  return validUntil !== null && validUntil.getTime() > now.getTime();
}
