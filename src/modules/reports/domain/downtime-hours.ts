/**
 * Простой измеряется полными часами.
 *
 * ПРАВИЛО. Единица учёта простоя — час, и только целый: 1, 2, 3. Неполный час
 * округляется вверх. Двадцать минут ожидания бетона — это час простоя, а не
 * 0,33.
 *
 * ПОЧЕМУ ВВЕРХ, А НЕ ПО-БЛИЖНЕМУ. Простой — не измерение, а основание для
 * разговора с заказчиком и подрядчиком. Округление вниз обнуляет короткие
 * остановки, из которых складывается смена: шесть двадцатиминутных ожиданий
 * превращаются в ноль, хотя машина стояла два часа. Вверх завышает на
 * известную и одинаковую для всех величину — меньше половины часа на запись, —
 * и это честнее, чем терять их совсем.
 *
 * ПОЧЕМУ ОДИН ВЛАДЕЛЕЦ. Простой вводят с телефона машиниста и из формы отчёта,
 * а правят поправкой. Три места с собственным округлением разошлись бы на
 * первой же правке, и одна и та же остановка попадала бы в отчёт по-разному в
 * зависимости от того, кто её записал.
 *
 * НОЛЬ ОСТАЁТСЯ НУЛЁМ. Поправка «на самом деле простоя не было» — законный
 * ответ, и превращать её в час нельзя.
 */

/** Больше суток один простой длиться не может. */
export const DOWNTIME_MAX_HOURS = 24;

/** Шаг ввода и минимум для полей ввода простоя. */
export const DOWNTIME_STEP_HOURS = 1;

export function roundDowntimeHours(hours: number): number {
  return hours > 0 ? Math.ceil(hours) : 0;
}

/**
 * Простой для показа: всегда полные часы.
 *
 * ПОЧЕМУ НЕ ОБЩИЙ `formatHours`. Тот же помощник рисует и отработанное время
 * смены, где «11 ч 30 мин» — правда. У простоя минут не бывает по правилу
 * учёта, и общий формат выводил «115 ч 36 мин» ровно там, где минут быть не
 * должно.
 *
 * ПОЧЕМУ ВВЕРХ. Тем же правилом, что и ввод. Записанные до правила дробные
 * значения (18 строк на 05.09.2026) поднимаются до полного часа, а не
 * показываются с минутами: две единицы измерения простоя на одном экране хуже
 * округления на известную величину.
 */
export function formatDowntimeHours(hours: number | null | undefined): string {
  if (hours == null || !Number.isFinite(hours) || hours <= 0) return '0 ч';
  return `${roundDowntimeHours(hours)} ч`;
}
