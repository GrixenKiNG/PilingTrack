import { getSettings } from '@/modules/settings';
import { PILE_JOURNAL_EXPORT_LIMIT, type PileJournalFilters } from './pile-journal-types';
import { listPilePassports } from './pile-journal-list';
import { pileJournalHeader } from './pile-journal-totals';
import { BLANK } from './pile-journal-form41';
import { SIGNERS, pileGroups, type AosrInput } from './pile-journal-aosr';
import type { XlsxCell } from '@/lib/xlsx-writer';

/**
 * Акт освидетельствования ответственных конструкций «Свайный фундамент» —
 * приложение № 4 к приказу Минстроя России от 16.05.2023 № 344/пр.
 *
 * Как и акт на погружение, берёт только принятые сваи. Пункт 3 ссылается на
 * акты скрытых работ (осмотр свай до погружения, погружение свай): их номеров и
 * дат в приложении нет, поэтому они печатаются пустыми для заполнения от руки.
 * Реквизиты заказчика и проектировщика, шифр проекта, сертификаты, испытания и
 * решение (п. 9) тоже заполняют в файле: справочника участников нет.
 */
export function aookRows({ rows, header, organisation, inn, truncated }: AosrInput): XlsxCell[][] {
  const accepted = rows.filter((row) => row.hasPassport && row.acceptance === 'ACCEPTED');
  const notAccepted = rows.filter((row) => row.hasPassport && row.acceptance !== 'ACCEPTED').length;
  const site = header.siteNames.join(', ') || BLANK;
  const builder = [organisation || BLANK, inn ? `ИНН ${inn}` : null].filter(Boolean).join(', ');
  const groups = pileGroups(accepted);

  return [
    ['Приложение № 4 к составу исполнительной документации (приказ Минстроя России от 16.05.2023 № 344/пр)'],
    ['Объект капитального строительства', site],
    ['Застройщик, технический заказчик, лицо, ответственное за эксплуатацию здания, сооружения, или региональный оператор', BLANK],
    ['Лицо, осуществляющее строительство, реконструкцию, капитальный ремонт', builder],
    ['Лицо, осуществляющее подготовку проектной документации', BLANK],
    [],
    ['АКТ освидетельствования строительных конструкций, устранение недостатков в которых невозможно без разборки или повреждения других строительных конструкций, и участков сетей инженерно-технического обеспечения (ответственных конструкций)'],
    [`№ ${BLANK}`, '«__» ____________ 20__ г.', '(дата составления акта)'],
    [],
    ...SIGNERS.flatMap((title) => [[title], [BLANK]]),
    ['произвели осмотр строительных конструкций, выполненных', organisation || BLANK],
    ['и составили настоящий акт о нижеследующем:'],
    [],
    ['1. К освидетельствованию предъявлены следующие строительные конструкции', 'Свайный фундамент'],
    ...groups.map((line) => ['', line]),
    ['', `Итого принятых свай: ${accepted.length} шт.`],
    ...(notAccepted > 0 ? [['', `Свай с решением «не разобрана» или «на добивку» в акт не включено: ${notAccepted}`]] : []),
    ['2. Строительные конструкции выполнены по проектной документации', BLANK, '(номер, реквизиты чертежей, наименование проектной и (или) рабочей документации)'],
    ['3. Освидетельствованы скрытые работы, которые оказывают влияние на безопасность строительных конструкций:'],
    ['', `осмотр свай до погружения — акт № ${BLANK} от ${BLANK}`],
    ['', `погружение свай — акт № ${BLANK} от ${BLANK}`],
    ['', `сварка секций и антикоррозионная обработка стыков (для составных свай) — акты № ${BLANK} от ${BLANK}`],
    ['4. При выполнении строительных конструкций применены', groups.join('; ') || BLANK, '(реквизиты сертификатов и паспортов завода-изготовителя)', BLANK],
    ['5. Предъявлены документы, подтверждающие соответствие строительных конструкций предъявляемым к ним требованиям, в том числе:'],
    ['', `а) исполнительная схема планового и высотного положения голов свай: ${BLANK}`],
    ['', `б) журнал погружения (забивки) свай, форма № 4.1 СП 392.1325800.2018, № ${BLANK}; сводная ведомость забитых свай (форма № 2.5 ВСН 012-88)`],
    ['6. Проведены необходимые испытания и опробования', BLANK, '(например, статические или динамические испытания свай)'],
    ['7. Даты', `начала работ: ${header.dateFrom ?? BLANK}`, `окончания работ: ${header.dateTo ?? BLANK}`],
    ['8. Предъявленные строительные конструкции выполнены в соответствии с техническими регламентами, иными нормативными правовыми актами и проектной документацией', BLANK],
    ['9. На основании изложенного (указать необходимые пункты):'],
    ['', 'а) разрешается использование конструкций по назначению'],
    ['', 'б) разрешается использование конструкций по назначению с нагружением в размере ____ % проектной нагрузки'],
    ['', `в) разрешается полное нагружение при выполнении следующих условий: ${BLANK}`],
    ['', `г) разрешается производство последующих работ: ${BLANK}`],
    ['Дополнительные сведения', BLANK],
    ['Акт составлен в', BLANK, 'экземплярах'],
    ['Приложения', BLANK, '(исполнительные схемы и чертежи, результаты экспертиз, обследований, лабораторных и иных испытаний)'],
    [],
    ...(truncated ? [[`Показаны первые ${PILE_JOURNAL_EXPORT_LIMIT} записей — сузьте период или объект`]] : []),
    ...SIGNERS.flatMap((title) => [[title], [BLANK], ['(фамилия, инициалы)', '(подпись)']]),
  ];
}

/** АООК «Свайный фундамент» в .xlsx по тем же фильтрам, что и журнал. */
export async function exportPileAookXlsx(filters: PileJournalFilters): Promise<Buffer> {
  const { buildXlsx } = await import('@/lib/xlsx-writer');
  const { timezone, companyName, inn } = await getSettings(filters.tenantId);
  const { rows, truncated, totals } = await listPilePassports({
    ...filters,
    limit: PILE_JOURNAL_EXPORT_LIMIT,
    timezone,
  });
  return buildXlsx([
    {
      name: 'АООК Свайный фундамент',
      rows: aookRows({
        rows,
        header: pileJournalHeader(rows, totals, timezone),
        organisation: companyName ?? '',
        inn: inn ?? '',
        truncated,
      }),
    },
  ]);
}
