export interface SafetyInstruction {
  code: string;
  title: string;
  version: string;
  /** Кому адресована — подсказка при выборе, а не право доступа. */
  audience: string;
  /**
   * Роли, которым инструкция ОБЯЗАТЕЛЬНА.
   *
   * Отсюда берётся «ожидают ознакомления»: работнику нужна та инструкция, что
   * назначена его роли, а не все подряд. Пустой список означал бы «никому не
   * обязательна» — такую инструкцию незачем и заводить.
   */
  requiredForRoles: readonly string[];
  /**
   * Через сколько месяцев повторный инструктаж.
   *
   * ДОПУЩЕНИЕ, КОТОРОЕ ЛЕГКО ПОМЕНЯТЬ. Свайные и стропальные работы отнесены к
   * работам повышенной опасности — для них норматив требует повторного
   * инструктажа раз в три месяца; для прочих работ срок вдвое больше. Если у
   * организации по положению об охране труда иначе, это одно число здесь, а
   * не переделка расчёта.
   */
  repeatMonths: number;
}

