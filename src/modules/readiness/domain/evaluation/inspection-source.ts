/**
 * Чей осмотр описывает машину на сейчас.
 *
 * ЗАЧЕМ ПРАВИЛО. Машину осматривают двое и по-разному. Механик ведёт журнал
 * ЕО/ТО: разобрал узел, заменил, закрыл запись. Машинист каждую смену проходит
 * предсменный чек-лист на своём телефоне. Оба описывают одну машину, и балл
 * состояния должен браться ровно из одного — из того, что новее.
 *
 * ЧТО БЫЛО НЕ ТАК. Сначала расчёт видел только журнал механика: машина с
 * пройденным утренним осмотром висела «Осмотр не завершён». Это починили — но
 * починили в другую крайность: сегодняшний осмотр машиниста стал побеждать
 * всегда, просто потому что он от машиниста. Механик, закрывший ремонт в два
 * часа дня, проигрывал утреннему обходу в семь, и готовность считалась по
 * состоянию машины ДО ремонта.
 *
 * Правило не смотрит, кто автор. Оно смотрит на время.
 */
export type InspectionSource = 'INSPECTION' | 'OPERATOR_CHECKLIST';

export interface InspectionCandidates {
  /** Когда завершён предсменный осмотр машиниста. */
  operatorAt: Date | null;
  /**
   * Относится ли осмотр машиниста к текущим производственным суткам.
   *
   * Отдельный признак, а не сравнение дат здесь: производственные сутки
   * считаются в поясе организации, и повторять эту арифметику в правиле
   * значило бы завести ей второй, расходящийся экземпляр.
   */
  operatorSameDay: boolean;
  /** Когда закрыт осмотр механика в журнале ЕО/ТО. */
  mechanicAt: Date | null;
}

/**
 * Осмотр, по которому считается состояние. `null` — сегодня не смотрел никто
 * и журнала тоже нет.
 *
 * Осмотр машиниста берётся только за сегодня: вчерашний чек-лист ничего не
 * говорит о машине сегодня, а журнал механика живёт дольше суток — ремонт
 * недельной давности остаётся фактом о машине.
 */
export function chooseInspectionSource(input: InspectionCandidates): InspectionSource | null {
  const operatorAt = input.operatorSameDay ? input.operatorAt : null;
  if (operatorAt !== null && (input.mechanicAt === null || operatorAt > input.mechanicAt)) {
    return 'OPERATOR_CHECKLIST';
  }
  if (input.mechanicAt !== null) return 'INSPECTION';
  return operatorAt !== null ? 'OPERATOR_CHECKLIST' : null;
}
