/**
 * Нормализация строки для поиска по спискам.
 *
 * В русских данных «ё» и «е» — одна буква: набранное «петр» должно находить
 * «Пётр», а «черемушки» — «Черёмушки». Регистр приводим к нижнему, а лишние
 * пробелы (двойные, из копипаста) схлопываем в один. Одну и ту же функцию
 * применяют и к строке запроса, и к полям, по которым ищут, — иначе половина
 * совпадений теряется.
 */
export function normalizeSearch(value: string): string {
  return value.trim().toLocaleLowerCase('ru').replace(/ё/g, 'е').replace(/\s+/g, ' ');
}