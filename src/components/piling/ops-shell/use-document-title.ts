'use client';

import { useEffect } from 'react';

const PRODUCT_NAME = 'PilingTrack';

/**
 * Заголовок вкладки браузера для экрана.
 *
 * Оболочка `(app)/layout.tsx` клиентская и экспортировать `metadata` не может,
 * а страницы разделов — тоже клиентские: шаблона `title.template` из
 * `src/app/layout.tsx` на них не хватает, и десять открытых вкладок админки
 * назывались одинаково («PilingTrack - Управление свайными работами»).
 * Хук ставит заголовок вкладки по названию экрана после монтирования.
 *
 * Ставить заголовок нужно на экране-маршруте (его рендерит `page.tsx`), а не
 * на вложенном компоненте: вложенные экраны (например, `AdminDlq` в «Настройках»)
 * живут внутри чужого маршрута и подменили бы его заголовок.
 */
export function useDocumentTitle(title: string) {
  useEffect(() => {
    document.title = `${title} — ${PRODUCT_NAME}`;
  }, [title]);
}