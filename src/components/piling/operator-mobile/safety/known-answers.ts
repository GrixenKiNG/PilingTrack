import {WIND_STOP_MS, type ChecklistStage, type OperatorMobileState} from '@/modules/operator-mobile/contracts';

/**
 * Пункты, ответ на которые система знает лучше человека.
 *
 * ЗАЧЕМ. Вопрос, ответ на который машина знает точнее человека, не несёт
 * информации, зато учит относиться к списку как к формальности — и заодно
 * обесценивает соседние вопросы, на которые ответить может только человек.
 *
 * ПРАВИЛО, КОТОРОЕ ЗДЕСЬ НЕЛЬЗЯ НАРУШАТЬ: система отвечает только когда факт
 * бесспорен и она им действительно владеет. Отсюда три следствия:
 *
 *  1. Ответ всегда «норма» и никогда «неисправность». Спорное состояние — повод
 *     спросить человека, а не решить за него.
 *  2. Нет данных — нет ответа. Молчащий сервис погоды возвращает пункт человеку,
 *     а не подставляет «норму» вместо неизвестного.
 *  3. Основание видно на экране и уходит в ответ примечанием. Проверяющий через
 *     полгода должен различать, что подтвердил человек, а что — программа.
 *
 * ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ.
 *
 * «Освещённость рабочей зоны достаточна» (SITE_READY). Система знает, что
 * сейчас темно, но не знает, включили ли прожекторы. Это разные утверждения, и
 * подменять второе первым нельзя.
 *
 * СИЗ. Их больше нет ни в одном чек-листе ТБ: проверка средств защиты —
 * ежедневная и живёт на допуске, одним местом на всю смену (решение владельца
 * 18.09.2026). Подставлять сюда её результат больше нечем и незачем.
 */
export interface KnownAnswer {
  /** Что видит человек вместо кнопок ответа. */
  fact: string;
}

/**
 * Ответы, которые подставляет система, ключ — идентификатор пункта.
 * Пустая карта — обычный случай: почти все пункты остаются за человеком.
 */
export function knownAnswers(
  stage: ChecklistStage,
  state: OperatorMobileState,
): Record<string, KnownAnswer> {
  const known: Record<string, KnownAnswer> = {};

  if (stage === 'TB_PILING') {
    // Ветер пункт показывает только при свежем прогнозе (условие WIND), и
    // порог остановки работ у продукта один — из work-warnings. Выше порога
    // ответа не подставляем: там уже висит красное STOP, и решение о подъёме
    // мачты принимает человек на площадке, а не расчёт по цифре из города.
    const wind = state.weather?.windMs ?? null;
    if (wind !== null && wind <= WIND_STOP_MS) {
      known.wind = {fact: `${format(wind)} м/с при пороге ${WIND_STOP_MS} м/с`};
    }
  }

  return known;
}

function format(value: number): string {
  return value.toFixed(1).replace('.', ',').replace(',0', '');
}
