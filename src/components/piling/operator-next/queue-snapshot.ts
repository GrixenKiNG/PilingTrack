import {pendingCount} from '@/components/piling/operator-mobile/offline-queue';

/**
 * Сколько СВОИХ записей лежит на устройстве прямо сейчас.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ. Закрытие смены обязано перечитать очередь
 * НЕПОСРЕДСТВЕННО перед `close-shift`, а не доверять числу, показанному на
 * предыдущем рендере: пока человек читал итоги, фоновая отправка могла
 * доставить часть записей или, наоборот, добавить новые.
 *
 * ПОЧЕМУ ИМПОРТ ТОЛЬКО НА ЧТЕНИЕ. `pendingCount` фильтрует записи по владельцу
 * и ничего не отправляет. Модуль `operator-next` не импортирует ни
 * `sendQueuedCommand`, ни `flushQueue`, ни `enqueue`: чужие записи на общем
 * планшете уходят только от их автора, когда он войдёт сам.
 *
 * Ошибку чтения не превращаем в «очередь пуста»: неизвестность — это не ноль,
 * и закрывать по ней смену нельзя. Поэтому при сбое возвращаем -1, а вызывающий
 * обязан трактовать это как «проверить не удалось».
 */
export function ownPendingCount(): number {
  try {
    return pendingCount();
  } catch {
    return -1;
  }
}
