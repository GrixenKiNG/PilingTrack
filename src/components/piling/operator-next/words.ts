/**
 * Ответ сервера человеческим языком.
 *
 * Правило 8 задания: ошибки сервера — по-русски, без технических текстов.
 * Технический ответ («Validation failed», «Ошибка 400») машинисту не полезен:
 * он не говорит, что делать. Здесь у каждой группы кодов есть фраза о том,
 * что произошло и что дальше.
 */
export function humanError(error: unknown): string {
  // Запись легла в очередь — это не отказ, а принятая к отправке запись.
  if (error instanceof QueuedOffline) return error.message;
  if (error instanceof ApiError) {
    if (error.status === 400) return 'Сервер не принял данные: проверьте заполненное и попробуйте ещё раз.';
    if (error.status === 401) return 'Вход истёк. Войдите снова — запись на устройстве не пропадёт.';
    if (error.status === 403) return 'Это действие вам недоступно. Обратитесь к диспетчеру.';
    if (error.status === 404) return 'Смена или установка на сервере не найдены. Обновите экран.';
    if (error.status === 409) return 'Смена на сервере уже в другом состоянии. Экран обновлён.';
    if (error.status === 429) return 'Слишком много запросов подряд. Подождите минуту и повторите.';
    if (error.status === 0) return 'Ответ пришёл не от сервера приложения — возможно, сеть требует входа (Wi-Fi).';
    if (error.status >= 500) return 'Сервер не справился. Данные на устройстве сохранены — повторите отправку.';
    return 'Сервер не принял запрос. Повторите — введённое сохранится.';
  }
  if (error instanceof Error && error.message) return error.message;
  return 'Не получилось. Проверьте связь и повторите.';
}

/** Метры погонные — одной строкой, как в сводках продукта. */
export function meters(value: number): string {
  return `${value.toFixed(1)} м.п.`;
}
