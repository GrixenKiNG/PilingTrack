/** Нижние вкладки экрана работы. Подписи — из макета F1. */
const DOCK: Record<string, ScreenId> = {
  Смена: 'F1',
  Работа: 'F3',
  Дефекты: 'F5',
  Машина: 'C2',
};

/** Следующий экран по порядку макета — запасной переход для всего остального. */
function nextScreen(from: ScreenId): ScreenId {
  const at = SCREEN_ORDER.indexOf(from);
  return SCREEN_ORDER[Math.min(at + 1, SCREEN_ORDER.length - 1)];
}

/**
 * Подпись элемента, по которой ищется переход: первая строка текста без
 * служебных пометок. `▲` и переносы строк в макете — оформление, а не имя
 * пункта, поэтому в ключ они не входят.
 */
export function elementLabel(text: string): string {
  return text.replace(/▲/g, '').split('\n')[0].replace(/ /g, ' ').replace(/\s+/g, ' ').trim();
}

export function resolveTarget(from: ScreenId, label: string, isDock: boolean): ScreenId | null {
  if (isDock) return DOCK[label] ?? null;
  const named = TRANSITIONS[from]?.[label];
  if (named) return named;
  return nextScreen(from);
}

