import { db } from '@/lib/db';

/**
 * Опознание — единственное место, которому нужен доступ к базе без организации.
 *
 * Замкнутый круг: чтобы политика RLS отдала строку, нужен тенант; а тенант
 * лежит в самой строке. Для запроса это разомкнуто — организацию несёт токен
 * сессии. Но у входа токена ещё нет, а у контроллера телеметрии его нет
 * никогда: он предъявляет ключ устройства, и организация тоже в строке ключа.
 *
 * Три места, где круг остаётся: поиск пользователя по email, поиск по
 * ПИН-коду и поиск ключа устройства. Всё остальное приложение работает
 * строго под своей организацией.
 *
 * Решение — не выключать RLS для этих таблиц, а на время одного запроса
 * переключить роль подключения на отдельную, которой политики не писаны.
 * Роль заведена узко: только `User` и `DeviceKey`, только чтение и правка
 * тех полей, которые опознание действительно меняет (обновление устаревшего
 * хеша пароля, отметка последнего использования ключа). Границу держит
 * Postgres, а не договорённость между файлами.
 *
 * `SET LOCAL ROLE` действует до конца транзакции — как и `set_config` в
 * доставке тенанта, и по той же причине: прод ходит через pgbouncer в режиме
 * транзакционного пулинга, где обычный `SET` не доживает до нужного запроса.
 *
 * Без переменной окружения (локальная разработка, CI, тесты) переключения не
 * происходит: там подключение и так суперпользовательское, RLS не действует,
 * а лишняя транзакция только замедлила бы вход.
 */

/** Имя роли берётся из окружения и подставляется в SQL — проверяем строго. */
const SAFE_ROLE_NAME = /^[a-z_][a-z0-9_]{0,62}$/;

function identityRole(): string | null {
  const role = process.env.DB_IDENTITY_ROLE?.trim();
  if (!role) return null;
  if (!SAFE_ROLE_NAME.test(role)) {
    throw new Error(
      `DB_IDENTITY_ROLE содержит недопустимое имя роли: ${role}. Ожидается [a-z_][a-z0-9_]*`,
    );
  }
  return role;
}

/** Клиент, которым выполняется опознание: транзакция или обычный. */
export type IdentityClient = Pick<typeof db, 'user' | 'deviceKey'>;

/**
 * Выполнить опознание — при настроенной роли внутри транзакции с
 * переключением, иначе напрямую.
 *
 * Возвращаемое значение прокидывается наружу как есть, поэтому вызывающий
 * код не знает, была транзакция или нет.
 */
export async function withIdentityRole<T>(
  run: (client: IdentityClient) => Promise<T>,
): Promise<T> {
  const role = identityRole();
  if (!role) return run(db);

  return db.$transaction(async (tx) => {
    // Имя роли нельзя передать параметром — SET ROLE не принимает
    // подстановки. Отсюда проверка регулярным выражением выше: она и есть
    // защита от подстановки произвольного SQL через переменную окружения.
    await tx.$executeRawUnsafe(`SET LOCAL ROLE "${role}"`);
    return run(tx);
  });
}
