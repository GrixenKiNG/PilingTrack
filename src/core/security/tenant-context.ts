import { AsyncLocalStorage } from 'node:async_hooks';

/**
 * Тенант текущего запроса — чтобы слой доступа к данным мог узнать его,
 * не получая параметром через всю цепочку вызовов.
 *
 * Зачем это нужно. RLS в Postgres читает переменную `app.current_tenant`.
 * Выставлять её умеет только тот, кто знает тенанта, а знает его
 * аутентификация — на верхнем краю запроса. Слой доступа к данным лежит на
 * нижнем. Протаскивать tenantId через каждый промежуточный вызов означало бы
 * править сотни сигнатур ради значения, которое ни одна из них не использует.
 *
 * Хранилище держит изменяемый объект, а не само значение. Обёртка маршрута
 * открывает пустой ящик в начале запроса, `requireAuth` кладёт туда тенанта,
 * когда тот становится известен. Иначе пришлось бы аутентифицировать дважды:
 * один раз в обёртке ради контекста и второй раз в обработчике.
 *
 * Границы применимости:
 * - только среда Node (`node:async_hooks`); на edge-рантайме недоступно;
 * - воркеры и планировщик через обёртки маршрутов не проходят — там контекст
 *   заводится своей точкой входа (шаг 3 плана перевода RLS в fail-closed);
 * - это НЕ проверка доступа. Значение отражает, кем представился запрос,
 *   и не заменяет ни `assertCan`, ни фильтр `where tenantId`.
 */
interface TenantContextStore {
  tenantId: string | null;
}

const storage = new AsyncLocalStorage<TenantContextStore>();

/**
 * Открыть контекст на время запроса. Тенант пока неизвестен — его положит
 * `requireAuth`, когда разберёт сессию.
 */
export function runWithTenantContext<T>(fn: () => T): T {
  return storage.run({ tenantId: null }, fn);
}

/**
 * Записать тенанта в открытый контекст.
 *
 * Вне контекста молча ничего не делает: этим путём ходят воркеры и тесты,
 * вызывающие `requireAuth` напрямую, и падать там не за что.
 *
 * Повторная запись другого тенанта в один и тот же запрос — это ошибка в
 * коде, а не данные: один запрос представляется одним тенантом. Молчаливая
 * перезапись означала бы, что часть запроса отработала под одним тенантом, а
 * часть под другим, и следов бы не осталось.
 */
export function setRequestTenantId(tenantId: string | null): void {
  const store = storage.getStore();
  if (!store) return;

  if (store.tenantId !== null && tenantId !== null && store.tenantId !== tenantId) {
    throw new Error(
      `Tenant context reassigned within one request: ${store.tenantId} -> ${tenantId}`
    );
  }

  store.tenantId = tenantId;
}

/**
 * Тенант текущего запроса или null, если контекст не открыт либо запрос
 * не аутентифицирован.
 *
 * Возвращает именно null, а не бросает: на шаге 1 читатели должны уметь
 * работать и без контекста — иначе включение сломало бы все пути разом.
 * Обязательность появится вместе с переводом политик в fail-closed.
 */
export function getRequestTenantId(): string | null {
  return storage.getStore()?.tenantId ?? null;
}

/** Открыт ли контекст. Нужно, чтобы отличить «нет контекста» от «нет тенанта». */
export function hasTenantContext(): boolean {
  return storage.getStore() !== undefined;
}
